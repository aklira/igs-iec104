"""The S5 load test: the points of the load station, and the statistics of the load client's output.

The load station is the same igs104-server binary, with a generated points file of 10 000 points: float
points that answer the general interrogation, a thousand of them changing with a time tag, and ten command
points. The file is written under bench/load/ at the start of the test and is not committed.
"""

from __future__ import annotations

import math
from pathlib import Path

from .compose import BENCH_DIR

LOAD_DIR = BENCH_DIR / "load"
POINTS_FILE = LOAD_DIR / "points.toml"
TOTAL_POINTS = 10_000
CHANGING_POINTS = 1_000
COMMAND_POINTS = 10
FIRST_COMMAND_POINT = 20_001


def write_points(
    changing: int = CHANGING_POINTS, path: Path = POINTS_FILE, stagger_ms: int = 0
) -> int:
    """Writes the load station's points, and returns how many information objects it answers. The
    first `changing` float points change once per second, so the station sends `changing` changes a second."""
    path.parent.mkdir(exist_ok=True)
    blocks: list[str] = [
        "# Generated by igs_bench/load.py for the S5 load test. Not committed.",
    ]
    for address in range(1, TOTAL_POINTS + 1):
        lines = ["[[point]]", f"address = {address}", 'kind = "float"', "group = 1"]
        if address <= changing:
            # Each changing point has its own period: with a stagger, the changes spread out instead of
            # arriving in one burst per second (the station has no initial offset per point).
            period = 1000 + (address - 1) * stagger_ms
            lines += [
                "stamped = true",
                'simulation = "ramp"',
                f"period_ms = {period}",
                "increment = 1",
            ]
        blocks.append("\n".join(lines))
    for index in range(COMMAND_POINTS):
        blocks.append(
            "\n".join(
                [
                    "[[point]]",
                    f"address = {FIRST_COMMAND_POINT + index}",
                    'kind = "single"',
                    "command = true",
                ]
            )
        )
    path.write_text("\n\n".join(blocks) + "\n", encoding="utf-8")
    return TOTAL_POINTS + COMMAND_POINTS


def percentile(values: list[float], fraction: float) -> float:
    """The nearest-rank percentile of the values (fraction 0.99 for the 99th)."""
    if not values:
        raise ValueError("no values")
    ordered = sorted(values)
    rank = max(1, math.ceil(fraction * len(ordered)))
    return ordered[rank - 1]


def parse_lines(output: str, prefix: str) -> list[str]:
    """The output lines of one kind (for example "spont ms=")."""
    return [line for line in output.splitlines() if line.startswith(prefix)]


def ms_values(output: str, prefix: str) -> list[float]:
    """The `ms=` values of the lines with the prefix."""
    values: list[float] = []
    for line in parse_lines(output, prefix):
        fields = dict(part.split("=", 1) for part in line.split() if "=" in part)
        values.append(float(fields["ms"]))
    return values
